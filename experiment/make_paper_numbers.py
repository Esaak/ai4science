"""Write paper/results.tex with the numbers quoted in the manuscript.

Every macro is computed from the saved step-4 outputs
(``experiment/results/summary.json`` and ``experiment/results/paired_errors.csv``);
nothing is typed by hand. The script also re-checks that the summary agrees with
the per-scene table, so a stale summary stops the build instead of reaching the
paper.

Usage, from the repository root::

    .venv/bin/python -m experiment.make_paper_numbers
    .venv/bin/python -m experiment.make_paper_numbers --check
"""

import argparse
import csv
import io
import json
import sys
from pathlib import Path

RESULTS = Path(__file__).resolve().parent / "results"
PAPER = Path(__file__).resolve().parents[1] / "paper"
OUTPUT = PAPER / "results.tex"
DESCRIPTION_THRESHOLD_M = 20.0
TOLERANCE = 1e-9


def read_table(path):
    rows = []
    with path.open(encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle, strict=True):
            rows.append({
                "geometry_id": int(row["geometry_id"]),
                "scene_name": row["scene_name"].strip(),
                "e_DL": float(row["e_DL"]),
                "e_Gaussian": float(row["e_Gaussian"]),
                "d": float(row["d"]),
            })
    rows.sort(key=lambda row: row["geometry_id"])
    if [row["geometry_id"] for row in rows] != list(range(150, 175)):
        raise ValueError("expected exactly one pair per geometry, IDs 150-174")
    return rows


def check_against_summary(rows, summary):
    """Fail loudly if summary.json and the per-scene table disagree."""
    n = len(rows)
    if summary["n"] != n:
        raise ValueError(f"summary n={summary['n']} but table has {n} rows")
    mean_d = sum(row["d"] for row in rows) / n
    if abs(mean_d - summary["mean_difference_m"]) > TOLERANCE:
        raise ValueError("mean difference in summary.json does not match the table")
    for row in rows:
        if abs((row["e_Gaussian"] - row["e_DL"]) - row["d"]) > TOLERANCE:
            raise ValueError(f"column d is inconsistent for geometry {row['geometry_id']}")
    for key, column in (("dl", "e_DL"), ("gaussian", "e_Gaussian")):
        count = sum(1 for row in rows if row[column] <= DESCRIPTION_THRESHOLD_M)
        if count != summary[key]["count_le_20_m"]:
            raise ValueError(f"count_le_20_m for {key} does not match the table")
    return mean_d


def fmt(value, digits=2):
    return f"{value:.{digits}f}"


def build_macros(rows, summary):
    n = len(rows)
    mean_d = summary["mean_difference_m"]
    low, high = summary["ci_95_m"]
    positive = [row for row in rows if row["d"] > 0]
    negative = [row for row in rows if row["d"] < 0]
    largest = max(rows, key=lambda row: row["d"])
    smallest = min(rows, key=lambda row: row["d"])
    worst_dl = max(rows, key=lambda row: row["e_DL"])
    worst_gaussian = max(rows, key=lambda row: row["e_Gaussian"])
    bootstrap = summary["bootstrap"]

    macros = {
        "NScenes": str(n),
        "MeanDiff": fmt(mean_d),
        "MeanDiffSigned": f"{mean_d:+.2f}",
        "CILow": fmt(low),
        "CIHigh": fmt(high),
        "MedianDL": fmt(summary["dl"]["median_m"]),
        "MedianGauss": fmt(summary["gaussian"]["median_m"]),
        "CountDL": str(summary["dl"]["count_le_20_m"]),
        "CountGauss": str(summary["gaussian"]["count_le_20_m"]),
        "ThresholdM": fmt(DESCRIPTION_THRESHOLD_M, 0),
        "NResamples": f"{bootstrap['resamples']:,}".replace(",", "{,}"),
        "BootstrapSeed": str(bootstrap["seed"]),
        "NPositive": str(len(positive)),
        "NNegative": str(len(negative)),
        "MaxDiff": fmt(largest["d"]),
        "MaxDiffScene": str(largest["geometry_id"]),
        "MinDiff": fmt(abs(smallest["d"])),
        "MinDiffScene": str(smallest["geometry_id"]),
        "MaxErrDL": fmt(worst_dl["e_DL"]),
        "MaxErrDLScene": str(worst_dl["geometry_id"]),
        "MaxErrGauss": fmt(worst_gaussian["e_Gaussian"]),
        "MaxErrGaussScene": str(worst_gaussian["geometry_id"]),
        "PythonVersion": summary["versions"]["python"],
        "NumpyVersion": summary["versions"]["numpy"],
        "MatplotlibVersion": summary["versions"]["matplotlib"],
    }
    return macros


def render(macros):
    lines = [
        "% Generated by experiment/make_paper_numbers.py from",
        "% experiment/results/summary.json and experiment/results/paired_errors.csv.",
        "% Do not edit by hand: rerun the script instead.",
    ]
    for name, value in macros.items():
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="compare with the existing results.tex instead of writing")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()

    summary = json.loads((RESULTS / "summary.json").read_text(encoding="utf-8"))
    rows = read_table(RESULTS / "paired_errors.csv")
    check_against_summary(rows, summary)
    text = render(build_macros(rows, summary))

    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.is_file() else ""
        if current != text:
            print(f"{args.output} is out of date; rerun without --check", file=sys.stderr)
            return 1
        print(f"{args.output} matches summary.json and paired_errors.csv")
        return 0

    args.output.write_text(text, encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
